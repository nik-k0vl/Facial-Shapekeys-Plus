def merge_hierarchies(snapshots, key_names):
    """Merge pre-join trees by exact key name, with the active object's snapshot first.

    Blender merges equally named shape keys itself. Each resulting key therefore has
    one position in the tree, taken from its first occurrence. Shared folders collect
    new children from subsequent snapshots, including nested folders. Their original
    icon and expansion settings also come from the first occurrence.
    """
    existing = set(key_names)
    nodes = {}
    vertex_groups = {}

    def visit(branch, metadata, parent=None):
        for item in branch:
            is_folder = isinstance(item, list)
            name = item[0] if is_folder else item

            if name not in existing:
                if is_folder:
                    visit(item[1:], metadata, parent)
                continue

            if name not in nodes:
                nodes[name] = (parent, is_folder)
                vertex_groups[name] = metadata[name]

            if is_folder:
                # A real shape key on the active mesh can share a name with a
                # source folder. Keep its type and promote that folder's children.
                next_parent = name if nodes[name][1] else parent
                visit(item[1:], metadata, next_parent)

    for branch, metadata in snapshots:
        visit(branch, metadata)

    # Keep any keys generated by Blender, and always keep the reference key first.
    for name in key_names:
        nodes.setdefault(name, (None, False))

    branches = {name: [name] if folder else name for name, (_, folder) in nodes.items()}
    tree = []
    reference = key_names[0]

    for name in [reference] + [name for name in nodes if name != reference]:
        parent, _ = nodes[name]
        if name != reference and parent in nodes and nodes[parent][1]:
            branches[parent].append(branches[name])
        else:
            tree.append(branches[name])

    return tree, vertex_groups
